//! MD5 and RC4, the two primitives the PDF standard security handler needs.
//!
//! Both are implemented here rather than pulled from a crate because they are
//! fixed, short algorithms and the whole point of this module is to carry no
//! PDF or crypto dependency. Neither is used for a security decision: House
//! PTRs ship with an empty user password and permission bits the reader is
//! expected to honour voluntarily, so this only reverses an obfuscation the
//! publisher applied to a public document.

pub(super) fn rc4(key: &[u8], data: &[u8]) -> Vec<u8> {
    let mut s: [u8; 256] = std::array::from_fn(|i| i as u8);
    let mut j = 0u8;
    for i in 0..256 {
        j = j.wrapping_add(s[i]).wrapping_add(key[i % key.len().max(1)]);
        s.swap(i, j as usize);
    }
    let (mut i, mut j) = (0u8, 0u8);
    data.iter()
        .map(|byte| {
            i = i.wrapping_add(1);
            j = j.wrapping_add(s[i as usize]);
            s.swap(i as usize, j as usize);
            let k = s[(s[i as usize].wrapping_add(s[j as usize])) as usize];
            byte ^ k
        })
        .collect()
}

