use proc_macro2::{TokenStream, TokenTree};
use quote::quote;
use syn::{
    Data, DeriveInput, Field, Fields, GenericArgument, GenericParam, Ident, LitStr, Path,
    PathArguments, Type, TypeParamBound, TypePath,
};

/// How a field's values become a column.
enum Mapping {
    Str,
    Copy,
    WidenSigned,
    WidenUnsigned,
    Usize,
    Isize,
    Raw,
    StrList,
    Probe,
    Skip,
}

#[derive(Clone, Copy)]
enum TimeKind {
    Datetime,
    Date,
}

struct TimeAttr {
    kind: TimeKind,
    unit: Option<LitStr>,
}

/// How an epoch integer is read out of the field.
#[derive(Clone, Copy)]
enum Epoch {
    Plain,
    Formatted,
}

#[derive(Default)]
struct FieldAttrs {
    skip: bool,
    flatten: bool,
    list: bool,
    nested: bool,
    nonzero: bool,
    rename: Option<String>,
    prefix: Option<String>,
    time_exempt: Option<LitStr>,
    time: Option<TimeAttr>,
}

pub(crate) fn expand(input: &DeriveInput) -> syn::Result<TokenStream> {
    let krate = crate_path(input)?;
    let fields = named_fields(input)?;
    let format_param = format_param(input);
    let name = &input.ident;
    let impl_ty = match format_param {
        Some(_) => quote! { #name<#krate::format::Both> },
        None => quote! { #name },
    };
    let checked_crate = std::env::var("CARGO_PKG_NAME")
        .is_ok_and(|n| n.starts_with("finance-query") && n != "finance-query-derive");
    let time_naming_test = if checked_crate {
        time_naming_test(name, &impl_ty, fields, &krate)?
    } else {
        TokenStream::new()
    };
    let columns = fields
        .iter()
        .map(|field| field_columns(field, &krate, format_param))
        .collect::<syn::Result<Vec<_>>>()?
        .into_iter()
        .flatten();
    let pl = quote! { #krate::polars::prelude };
    let nested = nested_fields(fields, format_param)?;
    let nested_methods = nested_methods(&nested, &krate, &pl);
    let trait_nested = if nested.is_empty() {
        TokenStream::new()
    } else {
        quote! {
            fn to_nested_dataframe(&self) -> #pl::PolarsResult<#pl::DataFrame> {
                Self::to_nested_dataframe(self)
            }

            fn vec_to_nested_dataframe(items: &[Self]) -> #pl::PolarsResult<#pl::DataFrame> {
                Self::vec_to_nested_dataframe(items)
            }
        }
    };

    Ok(quote! {
        #time_naming_test

        impl #impl_ty {
            #nested_methods

            /// Converts this struct to a single-row polars DataFrame.
            ///
            /// Scalar and enum fields become columns; fields marked
            /// `#[dataframe(flatten)]` contribute their own columns, prefixed
            /// with the field name. Other nested types are excluded; see `#[dataframe(nested)]`.
            ///
            /// This method is auto-generated by the `ToDataFrame` derive macro.
            pub fn to_dataframe(&self) -> #pl::PolarsResult<#pl::DataFrame> {
                Self::vec_to_dataframe(::core::slice::from_ref(self))
            }

            /// Converts a slice of structs to a multi-row polars DataFrame.
            ///
            /// Uses the same columns as [`to_dataframe`](Self::to_dataframe).
            ///
            /// This method is auto-generated by the `ToDataFrame` derive macro.
            pub fn vec_to_dataframe(items: &[Self]) -> #pl::PolarsResult<#pl::DataFrame> {
                let rows: ::std::vec::Vec<_> = items.iter().map(::core::option::Option::Some).collect();
                #pl::DataFrame::new_infer_height(
                    <Self as #krate::__dataframe::Columns>::columns(&rows, ""),
                )
            }
        }

        impl #krate::ToDataFrame for #impl_ty {
            fn to_dataframe(&self) -> #pl::PolarsResult<#pl::DataFrame> {
                Self::to_dataframe(self)
            }

            fn vec_to_dataframe(items: &[Self]) -> #pl::PolarsResult<#pl::DataFrame> {
                Self::vec_to_dataframe(items)
            }
            #trait_nested
        }

        impl #krate::__dataframe::Columns for #impl_ty {
            fn columns(
                rows: &[::core::option::Option<&Self>],
                prefix: &str,
            ) -> ::std::vec::Vec<#pl::Column> {
                let columns: ::std::vec::Vec<::std::vec::Vec<#pl::Column>> = ::std::vec![
                    #( ::std::iter::FromIterator::from_iter(#columns) ),*
                ];
                columns.into_iter().flatten().collect()
            }
        }
    })
}

/// Emits a test that checks the empty frame's column names against its time dtypes.
fn time_naming_test(
    name: &Ident,
    impl_ty: &TokenStream,
    fields: &syn::punctuated::Punctuated<Field, syn::Token![,]>,
    krate: &Path,
) -> syn::Result<TokenStream> {
    let mut exempt = Vec::new();
    for field in fields {
        let attrs = field_attrs(field)?;
        if let (Some(_), Some(ident)) = (&attrs.time_exempt, &field.ident) {
            exempt.push(attrs.rename.unwrap_or_else(|| ident.to_string()));
        }
    }
    let module = Ident::new(&format!("__dataframe_time_naming_{name}"), name.span());
    let label = name.to_string();
    Ok(quote! {
        #[cfg(test)]
        #[allow(non_snake_case)]
        mod #module {
            #[allow(unused_imports)]
            use super::*;

            #[test]
            fn time_columns_are_named_and_typed() {
                let frame = <super::#impl_ty>::vec_to_dataframe(&[]).unwrap();
                #krate::__dataframe::assert_time_naming(#label, &frame, &[#(#exempt),*]);
            }
        }
    })
}

/// Builds the expression yielding a field's columns, or `None` when the field is skipped.
fn field_columns(
    field: &Field,
    krate: &Path,
    format_param: Option<&Ident>,
) -> syn::Result<Option<TokenStream>> {
    let attrs = field_attrs(field)?;
    if attrs.skip || attrs.nested {
        return Ok(None);
    }
    let Some(ident) = &field.ident else {
        return Ok(None);
    };
    let column = attrs.rename.unwrap_or_else(|| ident.to_string());
    let (inner, access) = match option_inner(&field.ty) {
        Some(inner) => (inner, quote! { item.#ident.as_ref() }),
        None => (
            &field.ty,
            quote! { ::core::option::Option::Some(&item.#ident) },
        ),
    };
    let values = quote! { rows.iter().map(|row| row.and_then(|item| #access)) };

    if attrs.flatten {
        let nested_prefix = match attrs.prefix.as_deref() {
            Some("") => quote! { ::std::string::String::from(prefix) },
            Some(custom) => quote! { ::std::format!("{}{}_", prefix, #custom) },
            None => quote! { ::std::format!("{}{}_", prefix, #column) },
        };
        return Ok(Some(quote! {{
            let nested: ::std::vec::Vec<::core::option::Option<&#inner>> = #values.collect();
            <#inner as #krate::__dataframe::Columns>::columns(
                &nested,
                &#nested_prefix,
            )
        }}));
    }

    let pl = quote! { #krate::polars::prelude };
    let name = quote! { ::std::format!("{}{}", prefix, #column) };
    if let Some(time) = &attrs.time {
        let source = TimeSource {
            krate,
            format_param,
            field,
            inner,
            name: &name,
            values: &values,
        };
        return time_columns(&source, time, attrs.list, attrs.nonzero).map(Some);
    }
    let series = |convert: TokenStream| {
        quote! {
            [#pl::Column::from(<#pl::Series as #pl::NamedFrom<_, _>>::new(
                #name.into(),
                #values.map(#convert).collect::<::std::vec::Vec<_>>(),
            ))]
        }
    };
    let columns = match mapping(inner, format_param) {
        Mapping::Str => series(quote! { |v| v.map(::std::string::String::as_str) }),
        Mapping::Copy => series(quote! { |v| v.copied() }),
        Mapping::WidenSigned => series(quote! { |v| v.map(|v| i32::from(*v)) }),
        Mapping::WidenUnsigned => series(quote! { |v| v.map(|v| u32::from(*v)) }),
        Mapping::Usize => series(quote! { |v| v.map(|v| *v as u64) }),
        Mapping::Isize => series(quote! { |v| v.map(|v| *v as i64) }),
        Mapping::Raw => series(quote! { |v| v.and_then(|v| v.raw) }),
        Mapping::StrList if attrs.list => {
            quote! { [#krate::__dataframe::string_list(#name, #values)] }
        }
        _ if attrs.list => {
            return Err(syn::Error::new_spanned(
                &field.ty,
                "`list` requires a `Vec<String>` field",
            ));
        }
        Mapping::StrList => return Ok(None),
        Mapping::Probe => quote! {{
            use #krate::__dataframe::{ViaDisplay as _, ViaSkip as _};
            (&&#krate::__dataframe::Probe::<#inner>(::core::marker::PhantomData))
                .kind()
                .column(#name, #values)
        }},
        Mapping::Skip => return Ok(None),
    };
    Ok(Some(columns))
}

struct TimeSource<'a> {
    krate: &'a Path,
    format_param: Option<&'a Ident>,
    field: &'a Field,
    inner: &'a Type,
    name: &'a TokenStream,
    values: &'a TokenStream,
}

fn time_columns(
    source: &TimeSource,
    time: &TimeAttr,
    list: bool,
    nonzero: bool,
) -> syn::Result<TokenStream> {
    let TimeSource {
        krate,
        format_param,
        field,
        inner,
        name,
        values,
    } = *source;
    let helpers = quote! { #krate::__dataframe };
    let fail = |message: &str| Err(syn::Error::new_spanned(&field.ty, message));
    let (element, is_vec) = match vec_inner(inner) {
        Some(element) => (element, true),
        None => (inner, false),
    };
    if is_vec != list {
        return fail(if list {
            "`list` requires a `Vec` field"
        } else {
            "a `Vec` time field requires `list`"
        });
    }
    let Some(epoch) = epoch_source(element, format_param) else {
        if is_vec || !is_string(element) {
            return fail(
                "`datetime` and `date` support `i64`, `FormattedValue<i64>` and `String`, or a `Vec` of the integer types with `list`",
            );
        }
        if let Some(unit) = &time.unit {
            return Err(syn::Error::new_spanned(
                unit,
                "a `String` field takes `datetime` or `date` without a unit",
            ));
        }
        let helper = match time.kind {
            TimeKind::Datetime => quote! { rfc3339_datetime },
            TimeKind::Date => quote! { str_date },
        };
        return Ok(quote! {
            [#helpers::#helper(
                #name,
                #values.map(|v| v.map(::std::string::String::as_str)),
            )]
        });
    };
    let Some(unit) = &time.unit else {
        return fail("an integer time field needs a unit, such as `datetime = \"s\"`");
    };
    let unit = match unit.value().as_str() {
        "s" => quote! { Seconds },
        "ms" => quote! { Millis },
        "us" => quote! { Micros },
        _ => quote! { Nanos },
    };
    let unit = quote! { #helpers::EpochUnit::#unit };
    if !is_vec {
        let helper = match time.kind {
            TimeKind::Datetime => quote! { epoch_datetime },
            TimeKind::Date => quote! { epoch_date },
        };
        let scalar = match epoch {
            Epoch::Plain => quote! { |v| v.copied() },
            Epoch::Formatted => quote! { |v| v.and_then(|v| v.raw) },
        };
        return Ok(quote! {
            [#helpers::#helper(#name, #unit, #nonzero, #values.map(#scalar))]
        });
    }
    let each = match epoch {
        Epoch::Plain => quote! { |v| ::core::option::Option::Some(*v) },
        Epoch::Formatted => quote! { |v| v.raw },
    };
    let helper = match time.kind {
        TimeKind::Datetime => quote! { datetime_list },
        TimeKind::Date => quote! { date_list },
    };
    Ok(quote! {
        [#helpers::#helper(
            #name,
            #unit,
            #nonzero,
            #values.map(|v| v.map(|list| list.as_slice())),
            #each,
        )]
    })
}

fn epoch_source(ty: &Type, format_param: Option<&Ident>) -> Option<Epoch> {
    let Type::Path(type_path) = ty else {
        return None;
    };
    let last = type_path.path.segments.last()?;
    let wraps_i64 = first_generic(&last.arguments).is_some_and(is_i64);
    if format_param.is_some_and(|param| is_format_assoc_value(type_path, param)) {
        return wraps_i64.then_some(Epoch::Formatted);
    }
    match last.ident.to_string().as_str() {
        "i64" if last.arguments.is_empty() => Some(Epoch::Plain),
        "FormattedValue" if wraps_i64 => Some(Epoch::Formatted),
        _ => None,
    }
}

fn is_i64(ty: &Type) -> bool {
    matches!(ty, Type::Path(tp) if tp.path.is_ident("i64"))
}

fn mapping(ty: &Type, format_param: Option<&Ident>) -> Mapping {
    let Type::Path(type_path) = ty else {
        return Mapping::Skip;
    };
    if let Some(param) = format_param {
        if is_format_assoc_value(type_path, param) {
            return Mapping::Raw;
        }
        if mentions(ty, param) {
            return Mapping::Skip;
        }
    }
    let Some(last) = type_path.path.segments.last() else {
        return Mapping::Skip;
    };
    match last.ident.to_string().as_str() {
        "String" => Mapping::Str,
        "i32" | "i64" | "u32" | "u64" | "f32" | "f64" | "bool" => Mapping::Copy,
        "i8" | "i16" => Mapping::WidenSigned,
        "u8" | "u16" => Mapping::WidenUnsigned,
        "usize" => Mapping::Usize,
        "isize" => Mapping::Isize,
        "FormattedValue" => Mapping::Raw,
        "Vec" if first_generic(&last.arguments).is_some_and(is_string) => Mapping::StrList,
        "DateTime" | "NaiveDate" | "NaiveDateTime" | "NaiveTime" => Mapping::Skip,
        "Value"
            if type_path
                .path
                .segments
                .iter()
                .any(|s| s.ident == "serde_json") =>
        {
            Mapping::Skip
        }
        _ => Mapping::Probe,
    }
}

fn field_attrs(field: &Field) -> syn::Result<FieldAttrs> {
    let mut attrs = FieldAttrs::default();
    for attr in field
        .attrs
        .iter()
        .filter(|a| a.path().is_ident("dataframe"))
    {
        attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("skip") {
                attrs.skip = true;
            } else if meta.path.is_ident("flatten") {
                attrs.flatten = true;
            } else if meta.path.is_ident("list") {
                attrs.list = true;
            } else if meta.path.is_ident("nested") {
                attrs.nested = true;
            } else if meta.path.is_ident("nonzero") {
                attrs.nonzero = true;
            } else if meta.path.is_ident("rename") {
                attrs.rename = Some(meta.value()?.parse::<LitStr>()?.value());
            } else if meta.path.is_ident("time_exempt") {
                let reason = meta.value()?.parse::<LitStr>()?;
                if reason.value().trim().is_empty() {
                    return Err(syn::Error::new_spanned(
                        &reason,
                        "`time_exempt` needs a non-empty reason",
                    ));
                }
                attrs.time_exempt = Some(reason);
            } else if meta.path.is_ident("prefix") {
                let prefix = meta.value()?.parse::<LitStr>()?;
                if prefix.value().ends_with('_') {
                    return Err(syn::Error::new_spanned(
                        &prefix,
                        "`prefix` must not end in `_`, the derive appends it",
                    ));
                }
                attrs.prefix = Some(prefix.value());
            } else if meta.path.is_ident("datetime") || meta.path.is_ident("date") {
                if attrs.time.is_some() {
                    return Err(meta.error("only one of `datetime` and `date` is allowed"));
                }
                let kind = if meta.path.is_ident("date") {
                    TimeKind::Date
                } else {
                    TimeKind::Datetime
                };
                let unit = if meta.input.peek(syn::Token![=]) {
                    let unit: LitStr = meta.value()?.parse()?;
                    let allowed: &[&str] = match kind {
                        TimeKind::Datetime => &["s", "ms", "us", "ns"],
                        TimeKind::Date => &["s", "ms"],
                    };
                    if !allowed.contains(&unit.value().as_str()) {
                        return Err(syn::Error::new_spanned(
                            &unit,
                            format!("unit must be one of {}", allowed.join(", ")),
                        ));
                    }
                    Some(unit)
                } else {
                    None
                };
                attrs.time = Some(TimeAttr { kind, unit });
            } else {
                return Err(meta.error(
                    "expected `skip`, `flatten`, `list`, `nested`, `nonzero`, `datetime`, `date`, `rename = \"...\"`, `prefix = \"...\"` or `time_exempt = \"...\"`",
                ));
            }
            Ok(())
        })?;
    }
    if attrs.time.is_some() && (attrs.skip || attrs.flatten || attrs.nested) {
        return Err(syn::Error::new_spanned(
            field,
            "`datetime` and `date` cannot be combined with `skip`, `flatten` or `nested`",
        ));
    }
    if attrs.time_exempt.is_some() && (attrs.skip || attrs.flatten || attrs.nested) {
        return Err(syn::Error::new_spanned(
            field,
            "`time_exempt` cannot be combined with `skip`, `flatten` or `nested`",
        ));
    }
    if attrs.prefix.is_some() && !attrs.flatten {
        return Err(syn::Error::new_spanned(
            field,
            "`prefix` requires `flatten`",
        ));
    }
    if attrs.nonzero && attrs.time.as_ref().is_none_or(|time| time.unit.is_none()) {
        return Err(syn::Error::new_spanned(
            field,
            "`nonzero` requires `datetime = \"unit\"` or `date = \"unit\"`",
        ));
    }
    if attrs.nested && (attrs.skip || attrs.list || attrs.flatten) {
        return Err(syn::Error::new_spanned(
            field,
            "`nested` cannot be combined with `skip`, `list` or `flatten`",
        ));
    }
    Ok(attrs)
}

fn crate_path(input: &DeriveInput) -> syn::Result<Path> {
    let mut krate = syn::parse_quote!(::finance_query);
    for attr in input
        .attrs
        .iter()
        .filter(|a| a.path().is_ident("dataframe"))
    {
        attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("crate") {
                krate = meta.value()?.parse::<LitStr>()?.parse()?;
                Ok(())
            } else {
                Err(meta.error("expected `crate = \"...\"`"))
            }
        })?;
    }
    Ok(krate)
}

fn named_fields(
    input: &DeriveInput,
) -> syn::Result<&syn::punctuated::Punctuated<Field, syn::Token![,]>> {
    match &input.data {
        Data::Struct(data) => match &data.fields {
            Fields::Named(fields) => Ok(&fields.named),
            _ => Err(syn::Error::new_spanned(
                input,
                "ToDataFrame only supports structs with named fields",
            )),
        },
        _ => Err(syn::Error::new_spanned(
            input,
            "ToDataFrame only supports structs",
        )),
    }
}

/// The struct's type parameter bounded by `Format`, if any.
fn format_param(input: &DeriveInput) -> Option<&Ident> {
    input.generics.params.iter().find_map(|param| match param {
        GenericParam::Type(param)
            if param.bounds.iter().any(|bound| {
                matches!(bound, TypeParamBound::Trait(tb)
                    if tb.path.segments.last().is_some_and(|s| s.ident == "Format"))
            }) =>
        {
            Some(&param.ident)
        }
        _ => None,
    })
}

fn option_inner(ty: &Type) -> Option<&Type> {
    let Type::Path(type_path) = ty else {
        return None;
    };
    let last = type_path.path.segments.last()?;
    if last.ident != "Option" {
        return None;
    }
    first_generic(&last.arguments)
}

fn first_generic(arguments: &PathArguments) -> Option<&Type> {
    let PathArguments::AngleBracketed(args) = arguments else {
        return None;
    };
    args.args.iter().find_map(|arg| match arg {
        GenericArgument::Type(ty) => Some(ty),
        _ => None,
    })
}

fn is_string(ty: &Type) -> bool {
    matches!(ty, Type::Path(tp) if tp.path.segments.last().is_some_and(|s| s.ident == "String"))
}

/// Matches `PARAM::Value<T>`, the associated type a `F: Format` struct uses for formatted values.
fn is_format_assoc_value(type_path: &TypePath, param: &Ident) -> bool {
    let segs = &type_path.path.segments;
    segs.len() == 2 && segs[0].ident == *param && segs[1].ident == "Value"
}

fn mentions(ty: &Type, param: &Ident) -> bool {
    fn walk(tokens: TokenStream, param: &Ident) -> bool {
        tokens.into_iter().any(|token| match token {
            TokenTree::Ident(ident) => ident == *param,
            TokenTree::Group(group) => walk(group.stream(), param),
            _ => false,
        })
    }
    walk(quote! { #ty }, param)
}

struct NestedField<'a> {
    ident: &'a Ident,
    column: String,
    inner: &'a Type,
    shape: Shape,
}

#[derive(Clone, Copy)]
enum Shape {
    Vec,
    OptionVec,
    One,
    OptionOne,
}

fn nested_fields<'a>(
    fields: &'a syn::punctuated::Punctuated<Field, syn::Token![,]>,
    format_param: Option<&Ident>,
) -> syn::Result<Vec<NestedField<'a>>> {
    let attrs = fields
        .iter()
        .map(field_attrs)
        .collect::<syn::Result<Vec<_>>>()?;
    let taken: Vec<String> = fields
        .iter()
        .zip(&attrs)
        .filter(|(_, attrs)| !attrs.skip && !attrs.nested)
        .filter_map(|(field, attrs)| {
            let ident = field.ident.as_ref()?;
            Some(attrs.rename.clone().unwrap_or_else(|| ident.to_string()))
        })
        .collect();
    let mut nested: Vec<NestedField> = Vec::new();
    for (field, attrs) in fields.iter().zip(attrs) {
        let Some(ident) = &field.ident else {
            continue;
        };
        if !attrs.nested {
            continue;
        }
        if format_param.is_some_and(|param| mentions(&field.ty, param)) {
            return Err(syn::Error::new_spanned(
                field,
                "nested fields can't use the format parameter",
            ));
        }
        let (optional, ty) = match option_inner(&field.ty) {
            Some(inner) => (true, inner),
            None => (false, &field.ty),
        };
        let (shape, inner) = match vec_inner(ty) {
            Some(inner) if optional => (Shape::OptionVec, inner),
            Some(inner) => (Shape::Vec, inner),
            None if optional => (Shape::OptionOne, ty),
            None => (Shape::One, ty),
        };
        let column = attrs.rename.unwrap_or_else(|| ident.to_string());
        if taken.contains(&column) || nested.iter().any(|other| other.column == column) {
            return Err(syn::Error::new_spanned(
                field,
                format!("nested column `{column}` collides with another column; use `rename`"),
            ));
        }
        nested.push(NestedField {
            ident,
            column,
            inner,
            shape,
        });
    }
    Ok(nested)
}

fn vec_inner(ty: &Type) -> Option<&Type> {
    let Type::Path(type_path) = ty else {
        return None;
    };
    let last = type_path.path.segments.last()?;
    if last.ident != "Vec" {
        return None;
    }
    first_generic(&last.arguments)
}

/// The child rows of one parent as a `&[T]`.
fn rows_of(field: &NestedField, parent: TokenStream) -> TokenStream {
    let ident = field.ident;
    match field.shape {
        Shape::Vec => quote! { #parent.#ident.as_slice() },
        Shape::OptionVec => quote! { #parent.#ident.as_deref().unwrap_or_default() },
        Shape::One => quote! { ::core::slice::from_ref(&#parent.#ident) },
        Shape::OptionOne => quote! { #parent.#ident.as_slice() },
    }
}

fn nested_methods(nested: &[NestedField], krate: &Path, pl: &TokenStream) -> TokenStream {
    if nested.is_empty() {
        return TokenStream::new();
    }
    let frames = nested.iter().map(|field| {
        let ident = field.ident;
        let method = quote::format_ident!("{}_dataframe", ident);
        let inner = field.inner;
        let body = match field.shape {
            Shape::Vec | Shape::OptionVec => {
                let rows = rows_of(field, quote! { self });
                quote! { <#inner as #krate::ToDataFrame>::vec_to_dataframe(#rows) }
            }
            Shape::One => quote! { <#inner as #krate::ToDataFrame>::to_nested_dataframe(&self.#ident) },
            Shape::OptionOne => quote! {
                match &self.#ident {
                    ::core::option::Option::Some(item) => <#inner as #krate::ToDataFrame>::to_nested_dataframe(item),
                    ::core::option::Option::None => <#inner as #krate::ToDataFrame>::vec_to_nested_dataframe(&[]),
                }
            },
        };
        let summary = match field.shape {
            Shape::Vec | Shape::OptionVec => {
                format!("Converts the `{ident}` rows to a DataFrame with the row type's columns.")
            }
            Shape::One | Shape::OptionOne => format!(
                "Converts `{ident}` to a one-row DataFrame, with a `List(Struct)` column for each of its own nested fields."
            ),
        };
        let doc = format!(
            "{summary}\n\nThis method is auto-generated by the `ToDataFrame` derive macro."
        );
        quote! {
            #[doc = #doc]
            pub fn #method(&self) -> #pl::PolarsResult<#pl::DataFrame> {
                #body
            }
        }
    });
    let columns = nested.iter().map(|field| {
        let inner = field.inner;
        let name = &field.column;
        let rows = rows_of(field, quote! { item });
        quote! {
            frame.with_column(#krate::__dataframe::nested_column::<#inner>(
                #name,
                items.iter().map(|item| #rows),
            )?)?;
        }
    });
    quote! {
        #(#frames)*

        /// Converts this struct to a single-row DataFrame with its nested rows as columns.
        ///
        /// Has the columns of [`to_dataframe`](Self::to_dataframe), then one
        /// `List(Struct)` column per nested field holding that field's rows.
        ///
        /// This method is auto-generated by the `ToDataFrame` derive macro.
        pub fn to_nested_dataframe(&self) -> #pl::PolarsResult<#pl::DataFrame> {
            Self::vec_to_nested_dataframe(::core::slice::from_ref(self))
        }

        /// Converts a slice of structs to a multi-row DataFrame with nested rows as columns.
        ///
        /// Uses the same columns as [`to_nested_dataframe`](Self::to_nested_dataframe).
        ///
        /// This method is auto-generated by the `ToDataFrame` derive macro.
        pub fn vec_to_nested_dataframe(items: &[Self]) -> #pl::PolarsResult<#pl::DataFrame> {
            let mut frame = Self::vec_to_dataframe(items)?;
            #(#columns)*
            ::core::result::Result::Ok(frame)
        }
    }
}
