use proc_macro2::{TokenStream, TokenTree};
use quote::quote;
use syn::{
    Data, DeriveInput, Field, Fields, GenericArgument, GenericParam, Ident, LitStr, Path,
    PathArguments, Type, TypeParamBound, TypePath,
};

/// How a field's values become a column.
enum Mapping {
    Str,
    Copy,
    Usize,
    Raw,
    StrList,
    Probe,
    Skip,
}

#[derive(Default)]
struct FieldAttrs {
    skip: bool,
    flatten: bool,
    rename: Option<String>,
}

pub(crate) fn expand(input: &DeriveInput) -> syn::Result<TokenStream> {
    let krate = crate_path(input)?;
    let fields = named_fields(input)?;
    let format_param = format_param(input);
    let name = &input.ident;
    let impl_ty = match format_param {
        Some(_) => quote! { #name<#krate::format::Both> },
        None => quote! { #name },
    };
    let columns = fields
        .iter()
        .map(|field| field_columns(field, &krate, format_param))
        .collect::<syn::Result<Vec<_>>>()?
        .into_iter()
        .flatten();
    let pl = quote! { #krate::polars::prelude };

    Ok(quote! {
        impl #impl_ty {
            /// Converts this struct to a single-row polars DataFrame.
            ///
            /// Scalar and enum fields become columns; fields marked
            /// `#[dataframe(flatten)]` contribute their own columns, prefixed
            /// with the field name. Other nested types are excluded.
            ///
            /// This method is auto-generated by the `ToDataFrame` derive macro.
            pub fn to_dataframe(&self) -> #pl::PolarsResult<#pl::DataFrame> {
                Self::vec_to_dataframe(::core::slice::from_ref(self))
            }

            /// Converts a slice of structs to a multi-row polars DataFrame.
            ///
            /// Uses the same columns as [`to_dataframe`](Self::to_dataframe).
            ///
            /// This method is auto-generated by the `ToDataFrame` derive macro.
            pub fn vec_to_dataframe(items: &[Self]) -> #pl::PolarsResult<#pl::DataFrame> {
                let rows: ::std::vec::Vec<_> = items.iter().map(::core::option::Option::Some).collect();
                #pl::DataFrame::new_infer_height(
                    <Self as #krate::__dataframe::Columns>::columns(&rows, ""),
                )
            }
        }

        impl #krate::ToDataFrame for #impl_ty {
            fn to_dataframe(&self) -> #pl::PolarsResult<#pl::DataFrame> {
                Self::to_dataframe(self)
            }

            fn vec_to_dataframe(items: &[Self]) -> #pl::PolarsResult<#pl::DataFrame> {
                Self::vec_to_dataframe(items)
            }
        }

        impl #krate::__dataframe::Columns for #impl_ty {
            fn columns(
                rows: &[::core::option::Option<&Self>],
                prefix: &str,
            ) -> ::std::vec::Vec<#pl::Column> {
                let columns: ::std::vec::Vec<::std::vec::Vec<#pl::Column>> = ::std::vec![
                    #( ::std::iter::FromIterator::from_iter(#columns) ),*
                ];
                columns.into_iter().flatten().collect()
            }
        }
    })
}

/// Builds the expression yielding a field's columns, or `None` when the field is skipped.
fn field_columns(
    field: &Field,
    krate: &Path,
    format_param: Option<&Ident>,
) -> syn::Result<Option<TokenStream>> {
    let attrs = field_attrs(field)?;
    if attrs.skip {
        return Ok(None);
    }
    let Some(ident) = &field.ident else {
        return Ok(None);
    };
    let column = attrs.rename.unwrap_or_else(|| ident.to_string());
    let (inner, access) = match option_inner(&field.ty) {
        Some(inner) => (inner, quote! { item.#ident.as_ref() }),
        None => (
            &field.ty,
            quote! { ::core::option::Option::Some(&item.#ident) },
        ),
    };
    let values = quote! { rows.iter().map(|row| row.and_then(|item| #access)) };

    if attrs.flatten {
        return Ok(Some(quote! {{
            let nested: ::std::vec::Vec<::core::option::Option<&#inner>> = #values.collect();
            <#inner as #krate::__dataframe::Columns>::columns(
                &nested,
                &::std::format!("{}{}_", prefix, #column),
            )
        }}));
    }

    let pl = quote! { #krate::polars::prelude };
    let name = quote! { ::std::format!("{}{}", prefix, #column) };
    let series = |convert: TokenStream| {
        quote! {
            [#pl::Column::new(
                #name.into(),
                #values.map(#convert).collect::<::std::vec::Vec<_>>(),
            )]
        }
    };
    let columns = match mapping(inner, format_param) {
        Mapping::Str => series(quote! { |v| v.map(::std::string::String::as_str) }),
        Mapping::Copy => series(quote! { |v| v.copied() }),
        Mapping::Usize => series(quote! { |v| v.map(|v| *v as u64) }),
        Mapping::Raw => series(quote! { |v| v.and_then(|v| v.raw) }),
        Mapping::StrList => quote! { [#krate::__dataframe::string_list(#name, #values)] },
        Mapping::Probe => quote! {{
            use #krate::__dataframe::{ViaDisplay as _, ViaSkip as _};
            (&&#krate::__dataframe::Probe::<#inner>(::core::marker::PhantomData))
                .kind()
                .column(#name, #values)
        }},
        Mapping::Skip => return Ok(None),
    };
    Ok(Some(columns))
}

fn mapping(ty: &Type, format_param: Option<&Ident>) -> Mapping {
    let Type::Path(type_path) = ty else {
        return Mapping::Skip;
    };
    if let Some(param) = format_param {
        if is_format_assoc_value(type_path, param) {
            return Mapping::Raw;
        }
        if mentions(ty, param) {
            return Mapping::Skip;
        }
    }
    let Some(last) = type_path.path.segments.last() else {
        return Mapping::Skip;
    };
    match last.ident.to_string().as_str() {
        "String" => Mapping::Str,
        "i8" | "i16" | "i32" | "i64" | "u8" | "u16" | "u32" | "u64" | "f32" | "f64" | "bool" => {
            Mapping::Copy
        }
        "usize" => Mapping::Usize,
        "FormattedValue" => Mapping::Raw,
        "Vec" if first_generic(&last.arguments).is_some_and(is_string) => Mapping::StrList,
        "DateTime" | "NaiveDate" | "NaiveDateTime" | "NaiveTime" => Mapping::Skip,
        _ => Mapping::Probe,
    }
}

fn field_attrs(field: &Field) -> syn::Result<FieldAttrs> {
    let mut attrs = FieldAttrs::default();
    for attr in field
        .attrs
        .iter()
        .filter(|a| a.path().is_ident("dataframe"))
    {
        attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("skip") {
                attrs.skip = true;
            } else if meta.path.is_ident("flatten") {
                attrs.flatten = true;
            } else if meta.path.is_ident("rename") {
                attrs.rename = Some(meta.value()?.parse::<LitStr>()?.value());
            } else {
                return Err(meta.error("expected `skip`, `flatten` or `rename = \"...\"`"));
            }
            Ok(())
        })?;
    }
    Ok(attrs)
}

fn crate_path(input: &DeriveInput) -> syn::Result<Path> {
    let mut krate = syn::parse_quote!(::finance_query);
    for attr in input
        .attrs
        .iter()
        .filter(|a| a.path().is_ident("dataframe"))
    {
        attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("crate") {
                krate = meta.value()?.parse::<LitStr>()?.parse()?;
                Ok(())
            } else {
                Err(meta.error("expected `crate = \"...\"`"))
            }
        })?;
    }
    Ok(krate)
}

fn named_fields(
    input: &DeriveInput,
) -> syn::Result<&syn::punctuated::Punctuated<Field, syn::Token![,]>> {
    match &input.data {
        Data::Struct(data) => match &data.fields {
            Fields::Named(fields) => Ok(&fields.named),
            _ => Err(syn::Error::new_spanned(
                input,
                "ToDataFrame only supports structs with named fields",
            )),
        },
        _ => Err(syn::Error::new_spanned(
            input,
            "ToDataFrame only supports structs",
        )),
    }
}

/// The struct's type parameter bounded by `Format`, if any.
fn format_param(input: &DeriveInput) -> Option<&Ident> {
    input.generics.params.iter().find_map(|param| match param {
        GenericParam::Type(param)
            if param.bounds.iter().any(|bound| {
                matches!(bound, TypeParamBound::Trait(tb)
                    if tb.path.segments.last().is_some_and(|s| s.ident == "Format"))
            }) =>
        {
            Some(&param.ident)
        }
        _ => None,
    })
}

fn option_inner(ty: &Type) -> Option<&Type> {
    let Type::Path(type_path) = ty else {
        return None;
    };
    let last = type_path.path.segments.last()?;
    if last.ident != "Option" {
        return None;
    }
    first_generic(&last.arguments)
}

fn first_generic(arguments: &PathArguments) -> Option<&Type> {
    let PathArguments::AngleBracketed(args) = arguments else {
        return None;
    };
    args.args.iter().find_map(|arg| match arg {
        GenericArgument::Type(ty) => Some(ty),
        _ => None,
    })
}

fn is_string(ty: &Type) -> bool {
    matches!(ty, Type::Path(tp) if tp.path.segments.last().is_some_and(|s| s.ident == "String"))
}

/// Matches `PARAM::Value<T>`, the associated type a `F: Format` struct uses for formatted values.
fn is_format_assoc_value(type_path: &TypePath, param: &Ident) -> bool {
    let segs = &type_path.path.segments;
    segs.len() == 2 && segs[0].ident == *param && segs[1].ident == "Value"
}

fn mentions(ty: &Type, param: &Ident) -> bool {
    fn walk(tokens: TokenStream, param: &Ident) -> bool {
        tokens.into_iter().any(|token| match token {
            TokenTree::Ident(ident) => ident == *param,
            TokenTree::Group(group) => walk(group.stream(), param),
            _ => false,
        })
    }
    walk(quote! { #ty }, param)
}
